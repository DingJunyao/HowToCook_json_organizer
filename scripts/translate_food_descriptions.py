def main():
    raw_path = Path("data/usda_nutrition_raw.json")
    out_path = Path("data/usda_nutrition.json")

    if not raw_path.exists():
        raise FileNotFoundError(f"原始数据文件不存在: {raw_path}")

    with open(raw_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    translated = 0
    for item in data:
        fdc_id = item["fdc_id"]
        if fdc_id in TRANSLATIONS:
            item["description_zh"] = TRANSLATIONS[fdc_id]
            translated += 1
        elif not item["description_zh"]:
            # 保留英文作为兜底
            item["description_zh"] = item["description"]

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"翻译完成: {translated}/{len(data)} 条")
    if translated < len(data):
        missing = [item for item in data if item["fdc_id"] not in TRANSLATIONS]
        print(f"未翻译 ({len(missing)} 条):")
        for item in missing[:20]:
            print(f"  {item['fdc_id']}: {item['description']}")
        if len(missing) > 20:
            print(f"  ... 还有 {len(missing) - 20} 条")


if __name__ == "__main__":
    main()
